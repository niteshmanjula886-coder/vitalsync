package com.simats.vitalsync.ui.theme

/**
 * Supported Theme Modes in VitalSync:
 * - SYSTEM: Automatically follows the device's system dark mode setting.
 * - LIGHT: Forces the light color palette.
 * - DARK: Forces the Carbon-Gray & Matte-Black dark color palette.
 */
enum class AppThemeMode {
    SYSTEM,
    LIGHT,
    DARK
}
